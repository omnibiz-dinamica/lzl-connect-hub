// Static build for shared hosting (Hostnet via FTP): `npm run build:static` → dist/
// Plain Vite SPA — no TanStack Start, Nitro, SSR or Cloudflare Worker. The Lovable build
// keeps using vite.config.ts unchanged.
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import { tanstackRouter } from '@tanstack/router-plugin/vite';
import { business, sectors, services } from './src/lib/lzl/config';

const root = fileURLToPath(new URL('.', import.meta.url));
const r = (p: string) => resolve(root, p);

// Public address of the site (e.g. https://www.lzlservices.be). Set SITE_URL in the GitHub
// repository variables; it is used for canonical links, hreflang, sitemap.xml and robots.txt.
const siteUrl = (process.env.SITE_URL || 'https://lzl-connect-hub.lovable.app').replace(/\/+$/, '');
process.env.VITE_STATIC_SITE = 'true';
process.env.VITE_SITE_URL = siteUrl;

const htaccess = `# LZL Services — static site (generated by vite.static.config.ts)
DirectoryIndex index.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /
  # Force HTTPS — uncomment once the SSL certificate is active on Hostnet:
  # RewriteCond %{HTTPS} !=on
  # RewriteCond %{HTTP:X-Forwarded-Proto} !https
  # RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
  # SPA fallback: every internal URL (/nl/contact, /fr/diensten/...) is served by index.html
  RewriteRule ^index\\.html$ - [L]
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteRule . /index.html [L]
</IfModule>

<IfModule mod_headers.c>
  <FilesMatch "\\.(js|css|woff2?|png|jpe?g|webp|avif|svg|ico)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "^index\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
`;

function sitemap() {
  const paths = [
    '', '/diensten', '/sectoren', '/werkgebied', '/over-ons', '/offerte', '/jobs', '/contact',
    '/privacy', '/cookies', '/voorwaarden',
    ...services.map((s) => `/diensten/${s.slug}`),
    ...sectors.map((s) => `/sectoren/${s.slug}`),
    ...business.cities.map((c) => `/werkgebied/${c.toLowerCase()}`),
  ];
  const urls = ['nl', 'fr'].flatMap((l) => paths.map((p) => `<url><loc>${siteUrl}/${l}${p}</loc></url>`));
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">${urls.join('')}</urlset>\n`;
}

const robots = `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`;

// Files uploaded in Lovable (logo, hero video) live in src/assets/*.asset.json as paths like
// /__l5e/assets-v1/<id>/lzl-logo.png that only Lovable's hosting serves. The static build copies
// each one into dist/ at that same path: from public/<filename> when present, otherwise
// downloaded from the published Lovable site (LOVABLE_URL).
const lovableUrl = (process.env.LOVABLE_URL || 'https://lzl-connect-hub.lovable.app').replace(/\/+$/, '');

async function copyLovableAssets(out: string) {
  const dir = r('src/assets');
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.asset.json'))) {
    const meta = JSON.parse(readFileSync(resolve(dir, file), 'utf8')) as { url: string; original_filename: string };
    const target = resolve(out, `.${meta.url}`);
    mkdirSync(dirname(target), { recursive: true });
    const local = r(`public/${meta.original_filename}`);
    if (existsSync(local)) {
      copyFileSync(local, target);
      continue;
    }
    try {
      const res = await fetch(`${lovableUrl}${meta.url}`, { signal: AbortSignal.timeout(30000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      writeFileSync(target, Buffer.from(await res.arrayBuffer()));
    } catch (error) {
      // ::warning:: shows up as an annotation in GitHub Actions.
      console.warn(`::warning::${meta.original_filename} not copied (${String(error)}). Add it as public/${meta.original_filename}.`);
    }
  }
}

// Writes the hosting files next to index.html once the bundle is on disk.
function hostingFiles(): Plugin {
  return {
    name: 'lzl-hosting-files',
    apply: 'build',
    async writeBundle(options) {
      const out = options.dir ?? r('dist');
      writeFileSync(resolve(out, '.htaccess'), htaccess);
      writeFileSync(resolve(out, 'sitemap.xml'), sitemap());
      writeFileSync(resolve(out, 'robots.txt'), robots);
      await copyLovableAssets(out);
    },
  };
}

export default defineConfig({
  root: r('static'),
  envDir: root,
  publicDir: r('public'),
  base: '/',
  resolve: {
    alias: [
      // No server on shared hosting: forms use the browser implementation instead.
      { find: /^@\/lib\/lzl\/submissions\.functions$/, replacement: r('static/submissions.static.ts') },
      { find: /^@tanstack\/react-start$/, replacement: r('static/react-start-shim.ts') },
      { find: /^@\//, replacement: `${r('src')}/` },
    ],
  },
  plugins: [
    tanstackRouter({
      target: 'react',
      autoCodeSplitting: true,
      routesDirectory: r('src/routes'),
      generatedRouteTree: r('static/routeTree.gen.ts'),
      // sitemap.xml is a server route on Lovable; the static build writes the file instead.
      routeFileIgnorePattern: 'sitemap',
    }),
    react(),
    tailwindcss(),
    hostingFiles(),
  ],
  build: {
    outDir: r('dist'),
    emptyOutDir: true,
  },
});
